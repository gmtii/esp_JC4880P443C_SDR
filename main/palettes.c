static uint16_t lerp_stops(const uint8_t stops[][3], int n_stops, float t)
{
    float pos, u;
    int i0, i1;

    if (t < 0.0f) t = 0.0f;
    if (t > 1.0f) t = 1.0f;
    pos = t * (float)(n_stops - 1);
    i0 = (int)pos;
    if (i0 > n_stops - 2) i0 = n_stops - 2; /* t = 1.0 exact edge */
    i1 = i0 + 1;
    u = pos - (float)i0;
    return rgb565((uint8_t)((float)stops[i0][0] + u * ((float)stops[i1][0] - (float)stops[i0][0])),
                  (uint8_t)((float)stops[i0][1] + u * ((float)stops[i1][1] - (float)stops[i0][1])),
                  (uint8_t)((float)stops[i0][2] + u * ((float)stops[i1][2] - (float)stops[i0][2])));
}

/* Fire: black -> red -> orange -> yellow -> white, independent per-channel ramps. */
static uint16_t eval_fire(float t)
{
    if (t < 1.0f / 3.0f)
    {
        return rgb565((uint8_t)(t * 3.0f * 255.0f), 0, 0);
    }
    if (t < 2.0f / 3.0f)
    {
        return rgb565(255, (uint8_t)((t - 1.0f / 3.0f) * 3.0f * 255.0f), 0);
    }
    if (t > 1.0f)
    {
        t = 1.0f;
    }
    return rgb565(255, 255, (uint8_t)((t - 2.0f / 3.0f) * 3.0f * 255.0f));
}

