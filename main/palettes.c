const char *palette_name(int id)
{
    return (id >= 0 && id < PALETTE_COUNT) ? k_names[id] : k_names[PALETTE_CLASSIC];
}

void palette_build_lut(int id, uint16_t lut[256])
{
    const uint16_t *ready = NULL;
    const uint8_t(*stops)[3] = k_stops_classic;
    int n_stops = 15;

    switch (id)
    {
    case PALETTE_GQRX:    ready = k_lut_gqrx; break;
    case PALETTE_INFERNO: ready = k_lut_inferno; break;
    case PALETTE_MAGMA:   ready = k_lut_magma; break;
    case PALETTE_PLASMA:  ready = k_lut_plasma; break;
    case PALETTE_TURBO:   ready = k_lut_turbo; break;
    case PALETTE_VIRIDIS: ready = k_lut_viridis; break;
    default: break;
    }
    if (ready != NULL)
    {
        memcpy(lut, ready, 256 * sizeof(uint16_t));
        return;
    }

    if (id == PALETTE_FIRE || id == PALETTE_GRAYSCALE)
    {
        for (int i = 0; i < 256; i++)
        {
            lut[i] = (id == PALETTE_FIRE) ? eval_fire((float)i * (1.0f / 255.0f))
                                          : rgb565((uint8_t)i, (uint8_t)i, (uint8_t)i);
        }
        return;
    }

    switch (id)
    {
    case PALETTE_ELECTRIC:      stops = k_stops_electric;      n_stops = 4;  break;
    case PALETTE_CLASSIC_GREEN: stops = k_stops_classic_green; n_stops = 13; break;
    case PALETTE_SMOKE:         stops = k_stops_smoke;         n_stops = 8;  break;
    case PALETTE_TEMPER_COLORS: stops = k_stops_temper_colors; n_stops = 22; break;
    case PALETTE_VIVID:         stops = k_stops_vivid;         n_stops = 23; break;
    case PALETTE_WEBSDR:        stops = k_stops_websdr;        n_stops = 5;  break;
    default:                    break; /* Classic */
    }
    for (int i = 0; i < 256; i++)
    {
        lut[i] = lerp_stops(stops, n_stops, (float)i * (1.0f / 255.0f));
    }
}
